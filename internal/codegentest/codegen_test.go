// The generated types, pinned at compile time.
var (
	_ *time.Time             = codegentest.Payout{}.PaidAt             // type: [string, "null"], required
	_ *int32                 = codegentest.Payout{}.Retries            // type: [integer, "null"], optional
	_ *codegentest.Fee       = codegentest.Payout{}.Parent             // oneOf: [$ref, {type: "null"}]
	_ *[]string              = codegentest.Payout{}.Tags               // type: [array, "null"]
	_ *[]any                 = codegentest.Payout{}.Pair               // prefixItems: untyped
	_ string                 = codegentest.Status("")                  // oneOf + const: a plain string, no constants
	_ codegentest.Fee        = codegentest.Payout{}.Fee                // $ref with a sibling constraint: the referenced type
	_ codegentest.Platform   = codegentest.PlatformIOS                 // enum: prefixed constants
	_ codegentest.PayoutKind = codegentest.PayoutKindPAYOUT            // type: string + const: a one-value enum
	_ codegentest.Payout     = codegentest.PayoutPaidJSONRequestBody{} // webhooks: body type
	// merge patch member: x-go-type nullable.Nullable + skip-optional-pointer
	_ nullable.Nullable[string] = codegentest.PayoutPatch{}.Note
	_ codegentest.PayoutPatch   = codegentest.PatchPayoutApplicationMergePatchPlusJSONRequestBody{}
)

// A merge patch member keeps absent, null and a value apart.
func TestMergePatchMemberHasThreeStates(t *testing.T) {
	t.Parallel()

	tests := []struct {
		body            string
		specified, null bool
		value           string
	}{
		{`{}`, false, false, ""},
		{`{"note":null}`, true, true, ""},
		{`{"note":"x"}`, true, false, "x"},
	}
	for _, tt := range tests {
		var p codegentest.PayoutPatch
		if err := json.Unmarshal([]byte(tt.body), &p); err != nil {
			t.Fatal(err)
		}
		if p.Note.IsSpecified() != tt.specified || p.Note.IsNull() != tt.null || p.Note.GetOrEmpty() != tt.value {
			t.Errorf("%s: specified %v null %v value %q", tt.body, p.Note.IsSpecified(), p.Note.IsNull(), p.Note.GetOrEmpty())
		}
		out, err := json.Marshal(p)
		if err != nil {
			t.Fatal(err)
		}
		if string(out) != tt.body {
			t.Errorf("round trip of %s gives %s", tt.body, out)
		}
	}
}

func TestNullableFieldsMarshal(t *testing.T) {
	t.Parallel()

	tests := []struct {
		field   string
		wantTag string
		meaning string
	}{
		{"PaidAt", "paidAt", "required and nullable: null is written, never omitted"},
		{"Retries", "retries,omitempty", "optional and nullable: absent and null are the same"},
		{"Parent", "parent,omitempty", "optional nullable $ref"},
	}
	typ := reflect.TypeFor[codegentest.Payout]()
	for _, tt := range tests {
		f, ok := typ.FieldByName(tt.field)
		if !ok {
			t.Fatalf("Payout has no field %s", tt.field)
		}
		if got := f.Tag.Get("json"); got != tt.wantTag {
			t.Errorf("%s json tag = %q, want %q (%s)", tt.field, got, tt.wantTag, tt.meaning)
		}
	}

	in := `{"fee":1,"id":"0192f3c4-7b1a-7cc0-9a51-3f2b8e4d6a10","kind":"PAYOUT","meta":{},"paidAt":null,"status":"PAID"}`
	var p codegentest.Payout
	if err := json.Unmarshal([]byte(in), &p); err != nil {
		t.Fatal(err)
	}
	out, err := json.Marshal(p)
	if err != nil {
		t.Fatal(err)
	}
	if string(out) != in {
		t.Fatalf("round trip\n got: %s\nwant: %s", out, in)
	}
}

// internal/apiv1 and this package must be generated by the same
// oapi-codegen, or this package stops testing what apiv1 gets.
func TestGeneratorVersionMatchesAPIV1(t *testing.T) {
	t.Parallel()

	version := regexp.MustCompile(`oapi-codegen/v2/cmd/oapi-codegen@(v[0-9.]+)`)
	read := func(path string) string {
		t.Helper()
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		m := version.FindSubmatch(data)
		if m == nil {
			t.Fatalf("%s pins no oapi-codegen version", path)
		}
		return string(m[1])
	}
	if here, apiv1 := read("generate.go"), read("../apiv1/generate.go"); here != apiv1 {
		t.Fatalf("oapi-codegen %s here, %s in internal/apiv1", here, apiv1)
	}
}
